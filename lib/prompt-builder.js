/**
 * 组装最终发给大模型的完整 System Prompt
 * @param {object} options
 * @param {object} options.config 数据库/后台配置对象
 * @param {string} options.persona 用户选择的人格（male / female / default）
 * @returns {string} 组装后的完整提示词
 */
export function buildFullSystemPrompt({ config = {}, persona = "default" } = {}) {
  const p = String(persona || "").trim().toLowerCase();
  const validPersona = p === "male" ? "male" : p === "female" ? "female" : "default";

  // 1. 获取对应性别人设文本（后台配置优先，留空则回退内置人设模板）
  let personaText = "";
  if (validPersona === "male") {
    personaText = String(config?.systemPromptMale || "").trim() || PERSONA_PROMPTS.male;
  } else if (validPersona === "female") {
    personaText = String(config?.systemPromptFemale || "").trim() || PERSONA_PROMPTS.female;
  } else {
    personaText = String(config?.systemPrompt || "").trim() || PERSONA_PROMPTS.default;
  }

  // 2. 获取公共底座文本（后台配置优先，留空则使用内置标准底座）
  const baseRules = String(config?.systemPromptBase || "").trim() || BASE_RULES;

  // 3. 智能判重融合：若老配置里已包含了大部分红线与气泡要求，避免重复追加
  const hasRulesAlready =
    personaText.includes("绝对红线") ||
    personaText.includes("气泡格式") ||
    (personaText.includes("不讲道理") && personaText.includes("一行一句"));

  if (hasRulesAlready) {
    return personaText;
  }

  return `${personaText}\n\n${baseRules}`;
}

