/* ------------------------------------------------------------ 危机词 */

/**
 * ⚠️ **危机词用正则，不用 includes**：
 *    中文没有词边界，`includes("消失")` 会把"我的焦虑**消失**了"判成危机 ——
 *    而"消失"恰恰是好转的信号。反过来，`includes("死")` 更离谱
 *    （"笑死我了""累死了"都不是危机）。
 *
 *    所以这里**全部要求上下文**：
 *      · 前一组：动词/意愿词 +（最多 6 字）+ 危机结果词
 *      · 后一组：本身就是完整危机表达，无需上下文
 *
 * ⚠️ 命中 = **跳过所有冷却与阈值，立即干预**。宁可多问一句，也不能漏。
 */
export const CRISIS_PATTERNS = [
  {
    label: "自杀念头",
    pattern:
      /(想|要|准备|打算|决定|不如|干脆|宁可|索性|考虑过).{0,6}(死|自杀|自残|轻生|了结|结束生命|离开这个世界|不活了)/,
  },
  {
    label: "活着没意思",
    pattern: /(不想活|活不下去|不想活了|活着没意思|活着没劲|没意思活着|死了算了|不如死了|死了更好|谁也別救我)/,
  },
  {
    label: "自伤方式",
    pattern: /(自杀|自残|割腕|割手|跳楼|跳桥|上吊|安眠药|烧炭|吞药)/,
  },
  {
    label: "告别/交代",
    pattern: /(遗书|告别信|最后一条消息|把我的东西都|告别这个世界|不用找我了|谢谢你们一直)/,
  },
];

/** 逐条检查是否命中危机（返回命中的标签，没命中返回 null） */
export function matchCrisis(text) {
  const content = String(text || "").slice(0, 500);
  if (!content) return null;

  for (const item of CRISIS_PATTERNS) {
    if (item.pattern.test(content)) return item.label;
  }
  return null;
}

