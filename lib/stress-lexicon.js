/* ------------------------------------------------------ 首字索引（加速） */

/**
 * 为词表建"首字索引"：匹配时先看文本里出现了哪些字，
 * 只遍历首字命中的那几条词 —— 几千条词表下能省掉大部分无效比较。
 */
export function buildIndex(wordMap) {
  const index = new Map();
  for (const [word, weight] of wordMap) {
    const first = word[0];
    if (!index.has(first)) index.set(first, []);
    index.get(first).push([word, weight]);
  }
  return index;
}

/** 提取文本里出现过的字符集合（用于首字索引预筛） */
export function collectChars(text) {
  const set = new Set();
  for (const char of text) set.add(char);
  return set;
}

